"""
Install a `commit-msg` git hook into every repo that forces the commit message
to lowercase.

For every git repo found under each `repos[].path` in config.yaml, this writes
`.git/hooks/commit-msg`. The hook rewrites the commit message file in place,
lowercasing every letter, so any commit created in that repo ends up with an
all-lowercase message.

The hook carries a marker line so this tool can recognise (for status / clear)
the hooks it installed and avoid clobbering unrelated, pre-existing hooks.

How to use:
    Edit config.yaml, then uncomment the action you want in the __main__ block:

        set_hooks()      # install the lowercase commit-msg hook in every repo
        clear_hooks()    # remove hooks previously installed by this tool
        hooks_status()   # show which repos have our hook installed
"""

import stat
import sys
from pathlib import Path
from typing import Any, Dict, List

from config_loader import load_config, log

HOOK_NAME = "commit-msg"
MARKER = "# git-config-manager:lowercase-commit-msg"

# POSIX sh hook. Git (including Git for Windows) runs hooks through its bundled
# shell, so a /bin/sh script is portable.
#   $1 = path to the commit message file
#   $2 = commit source: message (-m/-F), commit (-c/-C), template, or empty.
#        NOTE: `git merge` passes an EMPTY $2 and reads .git/MERGE_MSG, so merges
#        are detected via the file name / MERGE_HEAD, not $2. Also note that
#        `git commit --amend` does NOT set $2=commit (it is `message` with -m,
#        or empty in the editor), so amended messages ARE lowercased.
# We lowercase normal messages (including --amend), but leave merge / squash /
# reused (-c/-C) messages untouched.
HOOK_SCRIPT = f"""#!/bin/sh
{MARKER}
# Force normal commit messages to all-lowercase, but skip messages that were
# generated by a merge/squash or reused from an existing commit (-c/-C).
msg_file="$1"

# Skip reused messages (-c / -C) and squash.
case "$2" in
  commit|squash) exit 0 ;;
esac

# Skip merges: commit-msg passes an empty $2 for merges, so detect them by the
# message file name and by an in-progress merge/squash state.
case "$msg_file" in
  *MERGE_MSG|*SQUASH_MSG) exit 0 ;;
esac
git_dir=$(git rev-parse --git-dir 2>/dev/null)
if [ -n "$git_dir" ] && {{ [ -f "$git_dir/MERGE_HEAD" ] || [ -f "$git_dir/MERGE_MSG" ] || [ -f "$git_dir/SQUASH_MSG" ]; }}; then
  exit 0
fi

tmp_file="$msg_file.gcm.tmp"
tr '[:upper:]' '[:lower:]' < "$msg_file" > "$tmp_file" && mv "$tmp_file" "$msg_file"
"""


# --------------------------------------------------------------------------- #
# config
# --------------------------------------------------------------------------- #
def load_repos() -> List[Dict[str, Any]]:
    """Load and validate the `repos` list from config.yaml."""
    data = load_config()
    repos = data.get("repos")
    if not isinstance(repos, list) or not repos:
        log("Missing or empty 'repos' list in config.yaml", "ERROR")
        sys.exit(1)

    valid: List[Dict[str, Any]] = []
    for i, entry in enumerate(repos):
        if not isinstance(entry, dict) or "path" not in entry:
            log(f"repos[{i}] is missing a 'path'; skipping", "WARN")
            continue
        valid.append(entry)
    if not valid:
        log("No usable repos entries found in config.yaml", "ERROR")
        sys.exit(1)
    return valid


def find_repos(base: Path) -> List[Path]:
    """Return every git repository directory found under `base`."""
    found: List[Path] = []
    if not base.exists():
        log(f"Path does not exist: {base}", "WARN")
        return found
    for git_dir in base.rglob(".git"):
        if git_dir.is_dir():
            found.append(git_dir.parent)
    return sorted(found)


# --------------------------------------------------------------------------- #
# hook helpers
# --------------------------------------------------------------------------- #
def hook_path(repo: Path) -> Path:
    return repo / ".git" / "hooks" / HOOK_NAME


def is_our_hook(path: Path) -> bool:
    """True if the file exists and was installed by this tool (has our marker)."""
    if not path.is_file():
        return False
    try:
        return MARKER in path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False


def make_executable(path: Path) -> None:
    """Set the executable bit (harmless / no-op semantics on Windows)."""
    try:
        mode = path.stat().st_mode
        path.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError:
        pass


# --------------------------------------------------------------------------- #
# per-repo operations
# --------------------------------------------------------------------------- #
def set_repo_hook(repo: Path) -> None:
    hooks_dir = repo / ".git" / "hooks"
    dst = hook_path(repo)

    if dst.exists() and not is_our_hook(dst):
        log(f"A different {HOOK_NAME} hook already exists; skipping: {dst}", "SKIP")
        return

    if is_our_hook(dst):
        log(f"Hook already installed: {dst}", "SKIP")
        return

    hooks_dir.mkdir(parents=True, exist_ok=True)
    dst.write_text(HOOK_SCRIPT, encoding="utf-8", newline="\n")
    make_executable(dst)
    log(f"Installed {HOOK_NAME} hook: {dst}", "HOOK")


def clear_repo_hook(repo: Path) -> None:
    dst = hook_path(repo)
    if not dst.exists():
        log(f"No {HOOK_NAME} hook: {dst}", "SKIP")
        return
    if not is_our_hook(dst):
        log(f"{HOOK_NAME} hook not installed by this tool; leaving it: {dst}", "SKIP")
        return
    dst.unlink()
    log(f"Removed {HOOK_NAME} hook: {dst}", "CLEAR")


def status_repo_hook(repo: Path) -> None:
    dst = hook_path(repo)
    if is_our_hook(dst):
        state = "installed (by this tool)"
    elif dst.exists():
        state = "present (foreign hook, not ours)"
    else:
        state = "not installed"
    log(f"{repo}: {HOOK_NAME} {state}", "STATUS")


# --------------------------------------------------------------------------- #
# commands
# --------------------------------------------------------------------------- #
def _iter_repos(action) -> None:
    entries = load_repos()
    for entry in entries:
        base = Path(str(entry["path"]))
        log(f"Group: {entry.get('name', '?')}  ({base})", "GROUP")
        found = find_repos(base)
        if not found:
            log("No git repos found under this path.", "WARN")
        for repo in found:
            action(repo)
        print("=" * 60)


def set_hooks() -> None:
    """Install the lowercase commit-msg hook in every repo."""
    _iter_repos(set_repo_hook)


def clear_hooks() -> None:
    """Remove commit-msg hooks previously installed by this tool."""
    _iter_repos(clear_repo_hook)


def hooks_status() -> None:
    """Show which repos have our commit-msg hook installed."""
    _iter_repos(status_repo_hook)


# --------------------------------------------------------------------------- #
# entry point
# --------------------------------------------------------------------------- #
if __name__ == "__main__":
    # Uncomment the action you want to run:
    set_hooks()
